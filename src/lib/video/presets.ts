/* Illustrative cost comparison                                        */
/* ------------------------------------------------------------------ */

/** Simulated relative unit costs, USD. Not vendor pricing. */
const ILLUSTRATIVE = {
  planningPerSpot: 4,
  prototypePerSecond: 0.06,
  premiumPerSecond: 3.2,
  /** Share of shots that typically need premium regeneration. */
  escalationShare: 0.3,
};

export interface CostComparisonRow {
  durationSeconds: DurationTarget;
  prototypeFirstUsd: number;
  premiumEverywhereUsd: number;
  savingsUsd: number;
  savingsPct: number;
}

export function costComparison(durations: DurationTarget[] = [15, 30, 60]): CostComparisonRow[] {
  return durations.map((durationSeconds) => {
    const premium = durationSeconds * ILLUSTRATIVE.premiumPerSecond;
    const prototype =
      ILLUSTRATIVE.planningPerSpot +
      durationSeconds * ILLUSTRATIVE.prototypePerSecond +
      durationSeconds * ILLUSTRATIVE.escalationShare * ILLUSTRATIVE.premiumPerSecond;
    const round = (n: number) => Math.round(n * 100) / 100;
    return {
      durationSeconds,
      prototypeFirstUsd: round(prototype),
      premiumEverywhereUsd: round(premium),
      savingsUsd: round(premium - prototype),
      savingsPct: Math.round(((premium - prototype) / premium) * 100),
    };
  });
}

