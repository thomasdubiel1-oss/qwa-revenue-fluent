/** Providers referenced by a preset for a given resolved routing decision. */
export function stageOwnerLabel(owner: WorkflowStage["owner"]): string {
  switch (owner) {
    case "planning_provider":
      return "Planning hub";
    case "shot_provider":
      return "Shot provider";
    case "audio_provider":
      return "Voice provider";
    case "code_motion":
      return "Code motion";
    default:
      return "Human";
  }
}

/** Escalation rule: which ranked provider handles a failing prototype shot. */
export function escalationTargets(
  ranked: { providerId: ProviderId; eligible: boolean }[],
): ProviderId[] {
  return ranked.filter((r) => r.eligible).map((r) => r.providerId);
}
